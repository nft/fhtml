"""Render bench/out/agents/results.json into bench/agents/RESULTS.md:
per-agent marks by task and arm, and the bare→skill uplift summary."""

import json
from statistics import mean

MARKS = {"pass": "✓", "prop-partial": "~", "prop-fail": "c",
         "dom-fail": "c", "compile-fail": "✗", "timeout": "t"}
LEGEND = ("`✓` full pass · `~` properties partial · `c` compiles but "
          "DOM/property fail · `✗` did not compile · `t` timeout")


def _cellmark(recs):
    if not recs:
        return "·"
    return "".join(MARKS[r["status"]] for r in
                   sorted(recs, key=lambda r: r["rep"]))


def _rate(recs, pred):
    return f"{100 * sum(pred(r) for r in recs) / len(recs):.0f}%" if recs else "–"


def _mean(recs, key):
    vals = [r[key] for r in recs if r.get(key) is not None]
    return f"{mean(vals):.2f}" if vals else "–"


def write(results_path, out_path):
    with open(results_path) as fh:
        results = json.load(fh)
    results = [r for r in results if r["agent"] not in ("null", "noop")]

    agents = sorted({r["agent"] for r in results})
    tasks = sorted({r["task"] for r in results})
    lines = ["# Agent benchmark results", "",
             "Generated by `bench/agents/run.py` — do not edit. "
             "Protocol in [README.md](README.md).", "", LEGEND, ""]

    if not results:
        lines += ["No real-agent results yet (only null/noop validation "
                  "runs, or none at all)."]
    for agent in agents:
        arecs = [r for r in results if r["agent"] == agent]
        version = arecs[0]["agent_version"]
        manual = " (manual protocol — wall-clock only)" \
            if arecs[0].get("manual") else ""
        lines += [f"## {agent} `{version}`{manual}", "",
                  "| task | bare | skill |", "|---|---|---|"]
        for task in tasks:
            row = [task]
            for arm in ("bare", "skill"):
                row.append(_cellmark([r for r in arecs
                                      if r["task"] == task and r["arm"] == arm]))
            lines.append("| " + " | ".join(row) + " |")

        lines += ["", "| metric | bare | skill |", "|---|---|---|"]
        by_arm = {arm: [r for r in arecs if r["arm"] == arm]
                  for arm in ("bare", "skill")}
        rows = [
            ("compile rate", lambda rs: _rate(rs, lambda r: r["compile"])),
            ("full pass rate", lambda rs: _rate(rs, lambda r: r["status"] == "pass")),
            ("mean quality", lambda rs: _mean(
                [{"q": r["quality"]["score"]} for r in rs], "q")),
            ("mean duration (s)", lambda rs: _mean(rs, "duration_s")),
            ("mean cost (USD)", lambda rs: _mean(rs, "cost_usd")),
        ]
        for label, fn in rows:
            lines.append(f"| {label} | {fn(by_arm['bare'])} "
                         f"| {fn(by_arm['skill'])} |")
        lines.append("")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines) + "\n")
